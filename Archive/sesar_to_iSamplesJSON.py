def jsonFromSesar(
    igsn: str,
    database: str = "SESAR202504",
    user: str = "postgres",
    password: str = "smrpostgis",
    host: str = "127.0.0.1",
    port: int = 5432
) -> Optional[Dict]:
    """
    Extract sample data from SESAR database and format as iSamples JSON.
    
    This is a standalone function that queries PostgreSQL directly,
    without requiring Django or any ORM framework.
    
    Args:
        igsn: The sample IGSN identifier
        database: Database name
        user: Database user
        password: Database password
        host: Database host
        port: Database port
        
    Returns:
        Dictionary representing the iSamples JSON structure, or None if not found
        
    Example:
        >>> json_data = jsonFromSesar("IGSN12345", password="mypassword")
        >>> print(json.dumps(json_data, indent=2))
    """
    # Create database config
    db_config = DatabaseConfig(
        database=database,
        user=user,
        password=password,
        host=host,
        port=port
    )
    
    # Create extractor and get JSON
    extractor = SESARJSONExtractor(db_config)
    
    try:
        extractor.connect()
        json_output = extractor.build_isamples_json(igsn)
        return json_output
    except Exception as e:
        print(f"Error extracting sample data: {e}")
        raise
    finally:
        extractor.close()


