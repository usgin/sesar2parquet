"""
Standalone function to extract SESAR sample data and format as iSamples JSON.
No Django dependencies - uses direct PostgreSQL queries.
Generated by Claude-code based on sesar2025migrate/newdb/models.py, views.py,
and sesar2025migrate/templates/newdbtemplate/sample.json
SMR 2025-12-10
set up to work with 202504 version of SESAR database, before dumbing down.
"""
import psycopg2
from psycopg2.extras import RealDictCursor
from typing import Dict, List, Optional, Any
from dataclasses import dataclass
import json
import datetime


@dataclass
class DatabaseConfig:
    """Database connection configuration."""
    database: str = "SESAR202504"
    user: str = "postgres"
    password: str = "your_password"
    host: str = "127.0.0.1"
    port: int = 5432


class SESARJSONExtractor:
    """Extracts SESAR sample data and formats as iSamples JSON."""
    
    def __init__(self, db_config: DatabaseConfig):
        self.db_config = db_config
        self.conn = None
    
    def connect(self):
        """Establish database connection."""
        self.conn = psycopg2.connect(
            database=self.db_config.database,
            user=self.db_config.user,
            password=self.db_config.password,
            host=self.db_config.host,
            port=self.db_config.port,
        )
    
    def close(self):
        """Close database connection."""
        if self.conn:
            self.conn.close()
    
    def execute_query(self, query: str, params: tuple = None) -> List[Dict]:
        """Execute query and return results as list of dictionaries."""
        with self.conn.cursor(cursor_factory=RealDictCursor) as cursor:
            cursor.execute(query, params)
            return cursor.fetchall()
    
    def execute_query_one(self, query: str, params: tuple = None) -> Optional[Dict]:
        """Execute query and return single result as dictionary."""
        with self.conn.cursor(cursor_factory=RealDictCursor) as cursor:
            cursor.execute(query, params)
            result = cursor.fetchone()
            return dict(result) if result else None

    def format_iso8601(self, date_value) -> Optional[str]:
        """Convert date to ISO8601 format with 'T' separator."""
        if not date_value:
            return None

        try:
            # If it's already a datetime object
            if isinstance(date_value, datetime):
                return date_value.isoformat()

            # If it's a string, parse and convert
            if isinstance(date_value, str):
                dt = datetime.fromisoformat(date_value)
                return dt.isoformat()

            return str(date_value)
        except Exception as e:
            # Fallback: simple string replace
            return str(date_value).replace(' ', 'T', 1)
