    def build_isamples_json(self, igsn: str) -> Optional[Dict]:
        """
        Build iSamples JSON structure for a sample.
        Args:
            igsn: Sample IGSN identifier
        Returns:
            Dictionary representing iSamples JSON structure
        """
        # Get main sample record
        sample = self.get_sample_by_igsn(igsn)
        if not sample:
            return None
        
        sample_id = sample['sample_id']
        
        # Get all related data
        alt_names = self.get_additional_names(sample_id)
        parent = self.get_parent_sample(sample_id)
        children = self.get_child_samples(sample_id)
        
        # Get siblings if there's a parent
        siblings = []
        if parent and parent.get('related_sesar_sample_id'):
            siblings = self.get_sibling_samples(sample_id, parent['related_sesar_sample_id'])
        
        coordinates = self.get_geospatial_location(sample_id)
        materials = self.get_sample_materials(sample_id)
        resp_parties = self.get_responsible_parties(sample_id)
        current_archive = self.get_current_archive(sample_id)
        
        # Filter out current archive from responsible parties
        if resp_parties and current_archive:
            resp_parties = [rp for rp in resp_parties if rp['relation_type_id'] != 3]
        
        registrant = None
        if sample.get('cur_registrant_individual_id'):
            registrant = self.get_registrant(sample['cur_registrant_id'])
        
        owner = None
        if sample.get('cur_owner_individual_id') or sample.get('cur_owner_institution_id'):
            owner = self.get_registrant(sample['cur_owner_id'])
        
        links = self.get_publication_urls(sample_id)
        docs = self.get_sample_docs(sample_id)
        
        # Build description components
        collection_desc = self.build_collection_description(sample)
        vertical_pos = self.build_vertical_position(sample)
        sam_desc = self.build_sample_description(sample, coordinates)
        
        # Build JSON structure
        json_output = {
            "@schema": "iSamplesSchemaCore1.0.json",
            "@id": sample.get('igsn', ''),
            "label": sample.get('name', 'sample name missing'),
            "sample_identifier": sample.get('igsn', ''),
            "description": sam_desc
        }
        
        # Add context category
        if sample.get('sampled_feature_label'):
            json_output["has_context_category"] = [{
                "label": sample['sampled_feature_label'],
                "identifier": sample.get('sampled_feature_uri', 'http://www.opengis.net/def/nil/OGC/0/missing')
            }]
        
        # Add material categories
        material_categories = []
        
        # Verbatim material name
        if sample.get('material_name_verbatim'):
            material_categories.append({
                "label": sample['material_name_verbatim'],
                "scheme_name": "verbatim"
            })
        else:
            material_categories.append({"label": "missing"})
        
        # General material type
        if sample.get('general_material_label'):
            material_categories.append({
                "label": sample['general_material_label'],
                "identifier": sample.get('general_material_uri', 'http://www.opengis.net/def/nil/OGC/0/missing')
            })
        
        # Additional materials
        for mat in materials:
            # Don't duplicate general material type
            if mat.get('material_type_id') != sample.get('general_material_type_id'):
                material_categories.append({
                    "label": mat.get('label', 'material name missing'),
                    "identifier": mat.get('material_type_uri', 'http://www.opengis.net/def/nil/OGC/0/missing')
                })
        
        json_output["has_material_category"] = material_categories
        
        # Add sample object type
        if sample.get('sample_type_label'):
            json_output["has_sample_object_type"] = [{
                "label": sample['sample_type_label'],
                "identifier": sample.get('sample_type_uri_value', 'http://www.opengis.net/def/nil/OGC/0/missing')
            }]
        
        # Build produced_by (sampling event)
        produced_by = {"label": "sampling event"}
        
        if collection_desc:
            produced_by["description"] = collection_desc
        
        if sample.get('locality_feature_type'):
            produced_by["has_feature_of_interest"] = sample['locality_feature_type']
        
        if sample.get('cruise_field_prgrm_label'):
            produced_by["project"] = sample['cruise_field_prgrm_label']
        
        # Add responsible parties
        if resp_parties:
            responsibility = []
            for agent in resp_parties:
                agent_name = agent.get('individual_label') or agent.get('institution_label', 'agentName missing')
                responsibility.append({
                    "role": agent.get('relation_type_label', 'related agent'),
                    "name": agent_name
                })
            produced_by["responsibility"] = responsibility
        
        # Add result time
        if sample.get('collection_start_date') or sample.get('collection_end_date'):
            result_time = sample.get('collection_start_date') or sample.get('collection_end_date')
            produced_by["result_time"] = self.format_iso8601(result_time)
        
        # Build sampling site
        sampling_site = {
            "label": sample.get('locality_name', 'site label missing'),
            "place_name": [sample.get('locality_name', 'place name missing')]
        }
        
        # Add site description
        desc_parts = []
        if sample.get('locality_detail'):
            desc_parts.append(sample['locality_detail'])
        if sample.get('location_qualifier'):
            desc_parts.append(sample['location_qualifier'])
        
        if desc_parts:
            sampling_site["description"] = '; '.join(desc_parts)
        
        # Add sample location
        if vertical_pos or sample.get('latitude') or sample.get('longitude'):
            sample_location = {}
            
            if vertical_pos:
                sample_location["elevation"] = vertical_pos
            
            if sample.get('latitude'):
                sample_location["latitude"] = float(sample['latitude'])
            
            if sample.get('longitude'):
                sample_location["longitude"] = float(sample['longitude'])
            
            sampling_site["sample_location"] = sample_location
        
        produced_by["sampling_site"] = sampling_site
        json_output["produced_by"] = produced_by
        
        # Add registrant
        if registrant:
            registrant_name = registrant.get('individual_label') or registrant.get('institution_label', 'agent name missing')
            json_output["registrant"] = {"name": registrant_name}
        
        # Add timestamps
        if sample.get('last_update_date'):
            json_output["last_modified_time"] = self.format_iso8601(sample['last_update_date'])
        
        # Add sampling purpose
        if sample.get('purpose'):
            json_output["sampling_purpose"] = sample['purpose']
        
        # Build related resources
        related_resources = []
        
        # Add parent
        if parent:
            related_resources.append({
                "label": parent.get('parent_name', 'parent'),
                "relationship": "Parent sample",
                "target": parent.get('related_resource_uri', 'http://www.opengis.net/def/nil/OGC/0/missing')
            })
        
        # Add children
        for child in children:
            related_resources.append({
                "label": child.get('child_name', 'child'),
                "relationship": "Child sample",
                "target": child.get('child_igsn', 'http://www.opengis.net/def/nil/OGC/0/missing')
            })
        
        # Add siblings
        for sib in siblings:
            related_resources.append({
                "label": sib.get('sibling_name', 'sibling'),
                "relationship": "Sample from the same parent",
                "target": sib.get('sibling_igsn', 'http://www.opengis.net/def/nil/OGC/0/missing')
            })
        
        # Add publication links
        for link in links:
            if link.get('description'):
                llabel = link.get('description')
            else:
                llabel = 'pub name missing'

            related_resources.append({
                "label": llabel,
                "relationship": "related resource",
                "target": link.get('url', 'http://www.opengis.net/def/nil/OGC/0/missing')
            })
        
        # Add documents
        for doc in docs:
            related_resources.append({
                "label": doc.get('file_name', 'file path missing'),
                "relationship": "local SESAR file",
                "description": "contact SESAR to access this file"
            })
        
        if related_resources:
            json_output["related_resource"] = related_resources
        
        # Add curation
        if current_archive:
            curation = {"role": "current archive"}
            
            if current_archive.get('institution_label'):
                curation["curation_location"] = current_archive['institution_label']
            
            if current_archive.get('individual_label'):
                responsibility = {"name": current_archive['individual_label']}
                if current_archive.get('individual_uri'):
                    responsibility["identifier"] = current_archive['individual_uri']
                curation["responsibility"] = responsibility
            
            json_output["curation"] = curation
        
        # Add keywords
        keywords = []
        
        if sample.get('geologic_unit'):
            keywords.append({
                "keyword": sample['geologic_unit'],
                "scheme_name": "Geologic unit"
            })
        
        if sample.get('geologic_age_younger_label'):
            keyword = {
                "keyword": sample['geologic_age_younger_label'],
                "scheme_name": "Geologic age, younger bound"
            }
            if sample.get('geologic_age_younger_uri'):
                keyword["keyword_uri"] = sample['geologic_age_younger_uri']
            keywords.append(keyword)
        
        if sample.get('geologic_age_older_label'):
            keyword = {
                "keyword": sample['geologic_age_older_label'],
                "scheme_name": "Geologic age, older bound"
            }
            if sample.get('geologic_age_older_uri'):
                keyword["keyword_uri"] = sample['geologic_age_older_uri']
            keywords.append(keyword)
        
        if keywords:
            json_output["keywords"] = keywords
        
        return json_output


