    # Query Methods for Related Data
    # ========================================================================
    
    def get_sample_by_igsn(self, igsn: str) -> Optional[Dict]:
        """Get main sample record by IGSN."""
        query = """
            SELECT s.*,
                   s.primary_location_name name as locality_name,
                   s.locality_detail as locality_detail_full,
                   sft.label as sampled_feature_label,
                   gmt.label as general_material_label,
                   gmt.material_type_uri as general_material_uri,
                   st.label as sample_type_label,
                   st.sample_type_uri as sample_type_uri_value,
                   cm.label as collection_method_label,
                   p.label as platform_label,
                   lp.label as launch_platform_label,
                   cfi.label as cruise_field_prgrm_label,
                   gay.label as geologic_age_younger_label,
                   gay.geologic_time_interval_uri as geologic_age_younger_uri,
                   gao.label as geologic_age_older_label,
                   gao.geologic_time_interval_uri as geologic_age_older_uri,
                   cr.individual_id as cur_registrant_individual_id,
                   cr.institution_id as cur_registrant_institution_id,
                   co.individual_id as cur_owner_individual_id,
                   co.institution_id as cur_owner_institution_id
            FROM sample s
            LEFT JOIN material_type gmt ON s.general_material_type_id = gmt.material_type_id
            LEFT JOIN sample_type st ON s.sample_type_id = st.sample_type_id
            LEFT JOIN sampling_method cm ON s.collection_method_id = cm.collection_method_id
            LEFT JOIN platform p ON s.platform_id = p.platform_id
            LEFT JOIN platform lp ON s.launch_platform_id = lp.platform_id
            LEFT JOIN initiative cfi ON s.cruise_field_prgrm_id = cfi.initiative_id
            LEFT JOIN geologic_time_scale gay ON s.geologic_age_younger_id = gay.geologic_time_id
            LEFT JOIN geologic_time_scale gao ON s.geologic_age_older_id = gao.geologic_time_id
            LEFT JOIN sesar_user cr ON s.cur_registrant_id = cr.sesar_user_id
            LEFT JOIN sesar_user co ON s.cur_owner_id = co.sesar_user_id
            LEFT JOIN sampled_feature_type sft2 ON L.feature_type_id = sft2.feature_type_id
            WHERE s.igsn = %s
        """
        return self.execute_query_one(query, (igsn,))

    def get_additional_names(self, sample_id: int) -> List[str]:
        """Get additional names for sample."""
        query = """
            SELECT name FROM sample_additional_name 
            WHERE sample_id = %s
        """
        results = self.execute_query(query, (sample_id,))
        return [r['name'] for r in results] if results else []
    
    def get_parent_sample(self, sample_id: int) -> Optional[Dict]:
        """Get parent sample relationship."""
        query = """
            SELECT rr.*, s.igsn as parent_igsn, s.name as parent_name
            FROM related_resource rr
            LEFT JOIN sample s ON rr.related_sesar_sample_id = s.sample_id
            WHERE rr.sample_id = %s AND rr.relation_type_id = 1
        """
        return self.execute_query_one(query, (sample_id,))
    
    def get_sibling_samples(self, sample_id: int, parent_id: int) -> List[Dict]:
        """Get sibling samples (same parent)."""
        query = """
            SELECT rr.*, s.igsn as sibling_igsn, s.name as sibling_name
            FROM related_resource rr
            JOIN sample s ON rr.sample_id = s.sample_id
            WHERE rr.related_sesar_sample_id = %s 
            AND rr.relation_type_id = 1
            AND rr.sample_id != %s
        """
        return self.execute_query(query, (parent_id, sample_id))
    
    def get_child_samples(self, sample_id: int) -> List[Dict]:
        """Get child samples."""
        query = """
            SELECT rr.*, s.igsn as child_igsn, s.name as child_name
            FROM related_resource rr
            JOIN sample s ON rr.sample_id = s.sample_id
            WHERE rr.related_sesar_sample_id = %s 
            AND rr.relation_type_id = 1
        """
        return self.execute_query(query, (sample_id,))
    
    def get_geospatial_location(self, sample_id: int) -> Optional[Dict]:
        """Get geospatial location (UTM coordinates)."""
        query = """
            SELECT * FROM geospatial_location 
            WHERE sample_id = %s
        """
        return self.execute_query_one(query, (sample_id,))
    
    def get_sample_materials(self, sample_id: int) -> List[Dict]:
        """Get additional material types for sample."""
        query = """
            SELECT sm.*, mt.label, mt.material_type_uri
            FROM sample_material sm
            JOIN material_type mt ON sm.material_type_id = mt.material_type_id
            WHERE sm.sample_id = %s
        """
        return self.execute_query(query, (sample_id,))
    
    def get_responsible_parties(self, sample_id: int) -> List[Dict]:
        """Get responsible parties (agents) for sample."""
        query = """
            SELECT rsa.*,
                   rt.label as relation_type_label,
                   i.label as individual_label,
                   i.individual_uri,
                   inst.label as institution_label
            FROM related_sample_agent rsa
            LEFT JOIN relation_type rt ON rsa.relation_type_id = rt.relation_type_id
            LEFT JOIN individual i ON rsa.individual_id = i.individual_id
            LEFT JOIN institution inst ON rsa.institution_id = inst.institution_id
            WHERE rsa.sample_id = %s
        """
        return self.execute_query(query, (sample_id,))
    
    def get_current_archive(self, sample_id: int) -> Optional[Dict]:
        """Get current archive (relation_type_id = 3)."""
        query = """
            SELECT rsa.*,
                   i.label as individual_label,
                   i.individual_uri,
                   inst.label as institution_label
            FROM related_sample_agent rsa
            LEFT JOIN individual i ON rsa.individual_id = i.individual_id
            LEFT JOIN institution inst ON rsa.institution_id = inst.institution_id
            WHERE rsa.sample_id = %s AND rsa.relation_type_id = 3
        """
        return self.execute_query_one(query, (sample_id,))
    
    def get_registrant(self, sesar_user_id: int) -> Optional[Dict]:
        """Get registrant from sesar_user."""
        query = """
            SELECT su.*,
                   i.label as individual_label,
                   inst.label as institution_label
            FROM sesar_user su
            LEFT JOIN individual i ON su.individual_id = i.individual_id
            LEFT JOIN institution inst ON su.institution_id = inst.institution_id
            WHERE su.sesar_user_id = %s
        """
        return self.execute_query_one(query, (sesar_user_id,))
    
    def get_publication_urls(self, sample_id: int) -> List[Dict]:
        """Get publication URLs for sample."""
        query = """
            SELECT * FROM sample_publication_url 
            WHERE sample_id = %s
        """
        return self.execute_query(query, (sample_id,))
    
    def get_sample_docs(self, sample_id: int) -> List[Dict]:
        """Get sample documents."""
        query = """
            SELECT * FROM sample_doc 
            WHERE sample_id = %s
        """
        return self.execute_query(query, (sample_id,))
    
    # ========================================================================
    # Helper Methods for Building JSON Structure
    # ========================================================================
    
    def build_collection_description(self, sample: Dict) -> str:
        """Build collection description string."""
        parts = []
        
        if sample.get('collection_method_label'):
            parts.append(f"method:{sample['collection_method_label']}")
        
        if sample.get('collection_method_detail'):
            parts.append(sample['collection_method_detail'])
        
        if sample.get('platform_label'):
            parts.append(f"Platform: {sample['platform_label']}")
        
        if sample.get('launch_platform_label'):
            parts.append(f"Launch Platform: {sample['launch_platform_label']}")
        
        if sample.get('launch_label'):
            parts.append(f"Launch: {sample['launch_label']}")
        
        return '. '.join(parts) if parts else ''
    
    def build_vertical_position(self, sample: Dict) -> str:
        """Build vertical position string."""
        parts = []
        
        if sample.get('elevation'):
            parts.append(str(sample['elevation']))
            if sample.get('elevation_uom'):
                parts.append(f"UOM: {sample['elevation_uom']}")
        
        depth_min = sample.get('depth_min')
        depth_max = sample.get('depth_max')
        
        if depth_min or depth_max:
            if depth_min == depth_max:
                parts.append(f"Depth: {depth_min}")
            elif depth_min and depth_max:
                parts.append(f"Depth range: {depth_min} to {depth_max}")
            elif depth_min:
                parts.append(f"Depth minimum: {depth_min}")
            elif depth_max:
                parts.append(f"Depth maximum: {depth_max}")
            
            if sample.get('depth_uom'):
                parts.append(f"UOM: {sample['depth_uom']}")
        
        if sample.get('depth_spatial_ref'):
            parts.append(f"Datum: {sample['depth_spatial_ref']}")
        
        return ' '.join(parts) if parts else ''
    
    def build_sample_description(self, sample: Dict, coordinates: Optional[Dict]) -> str:
        """Build sample description string."""
        parts = []
        
        if sample.get('sample_description'):
            parts.append(sample['sample_description'])
        
        if sample.get('size'):
            parts.append(f"Sample size: {sample['size']}")
        
        # Lat/long ranges
        if sample.get('latitude') and sample.get('latitude_end'):
            parts.append(f"Latitude from {sample['latitude']} to {sample['latitude_end']}")
        
        if sample.get('longitude') and sample.get('longitude_end'):
            parts.append(f"Longitude from {sample['longitude']} to {sample['longitude_end']}")
        
        # UTM coordinates
        if coordinates:
            utm_parts = []
            if coordinates.get('coordinate_1'):
                utm_parts.append(f"Easting {coordinates['coordinate_1']}")
            if coordinates.get('coordinate_2'):
                utm_parts.append(f"Northing {coordinates['coordinate_2']}")
            if coordinates.get('spatial_reference_system'):
                utm_parts.append(f"Spatial reference: {coordinates['spatial_reference_system']}")
            
            if utm_parts:
                parts.append(f"UTM coordinates: {' '.join(utm_parts)}")
        
        # Numeric ages
        age_min = sample.get('numeric_age_min')
        age_max = sample.get('numeric_age_max')
        
        if age_min and age_max:
            parts.append(f"Age between {age_min} and {age_max}")
        elif age_min:
            parts.append(f"Minimum age {age_min}")
        elif age_max:
            parts.append(f"Maximum age {age_max}")
        
        if (age_min or age_max) and sample.get('numeric_age_unit'):
            parts.append(f"Age units {sample['numeric_age_unit']}")
        
        if sample.get('age_qualifier'):
            parts.append(f"Age qualifier: {sample['age_qualifier']}")
        
        return '. '.join(parts) if parts else ''
    
