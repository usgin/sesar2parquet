class CacheManager:
    def __init__(self, cache_dir: str = "cache"):
        self.cache_dir = pathlib.Path(cache_dir)
        self.cache_dir.mkdir(exist_ok=True)
    
    def load_or_create(self, name: str, create_func) -> Optional[Dict]:
        cache_path = self.cache_dir / f"{name}.pkl"
        
        if cache_path.exists():
            try:
                with open(cache_path, 'rb') as f:
                    logger.info(f"Loading {name} from cache")
                    return pickle.load(f)
            except Exception as e:
                logger.warning(f"Cache load failed for {name}: {e}")
        
        try:
            data = create_func()
            if data:
                with open(cache_path, 'wb') as f:
                    pickle.dump(data, f)
                logger.info(f"Created and cached {name}")
            return data
        except Exception as e:
            logger.error(f"Error creating {name}: {e}")
            return {}


