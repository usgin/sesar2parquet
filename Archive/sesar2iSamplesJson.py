@dataclass
class BatchStats:
    items_processed: int = 0
    items_failed: int = 0
    batches_flushed: int = 0
    start_time: float = field(default_factory=time.time)
    
    @property
    def items_per_second(self) -> float:
        elapsed = time.time() - self.start_time
        return self.items_processed / elapsed if elapsed > 0 else 0.0

class BatchProcessor:
    def __init__(self, batch_size: int = 1000, flush_callback=None):
        self.batch_size = batch_size
        self.flush_callback = flush_callback
        self._batch: List[Dict[str, Any]] = []
        self.stats = BatchStats()
        
    def add(self, item: Dict[str, Any]) -> None:
        try:
            self._batch.append(item)
            self.stats.items_processed += 1
            if len(self._batch) >= self.batch_size:
                self.flush()
        except Exception as e:
            self.stats.items_failed += 1
            logger.error(f"Error adding item: {e}")
    
    def flush(self) -> None:
        if not self._batch or not self.flush_callback:
            return
        try:
            self.flush_callback(self._batch)
            self.stats.batches_flushed += 1
            self._batch.clear()
            logger.info(f"Flushed batch. Total: {self.stats.items_processed}, "
                       f"Rate: {self.stats.items_per_second:.2f}/sec")
        except Exception as e:
            logger.error(f"Flush error: {e}")
            raise
    
    def finalize(self) -> BatchStats:
        if self._batch:
            self.flush()
        return self.stats
    
    @contextmanager
    def processing_context(self):
        try:
            yield self
        finally:
            self.finalize()


