    def create_sampling_event(self, sample_id: int, sample_data: Dict) -> Optional[int]:
        """Create SamplingEvent and return its row_id."""
        key = f"sample:{sample_id}"
        
        # Check if already created
        existing_id = self.registry.get_id('SamplingEvent', key)
        if existing_id:
            return existing_id
        
        # Build collection description
        desc_parts = []
        if sample_data.get('collection_method_label'):
            desc_parts.append(f"method:{sample_data['collection_method_label']}")
        if sample_data.get('collection_method_detail'):
            desc_parts.append(sample_data['collection_method_detail'])
        if sample_data.get('platform_label'):
            desc_parts.append(f"Platform: {sample_data['platform_label']}")
        if sample_data.get('launch_platform_label'):
            desc_parts.append(f"Launch Platform: {sample_data['launch_platform_label']}")
        if sample_data.get('launch_label'):
            desc_parts.append(f"Launch: {sample_data['launch_label']}")
        
        description = '; '.join(desc_parts) if desc_parts else None
        
        # Get collectors (responsibility)
        query = """
            SELECT individual_id, institution_id, agent_type
            FROM related_sample_agent
            WHERE sample_id = %s AND relation_type_id = 1
        """
        collectors = self.execute_pg_query(query, (sample_id,))
        
        responsibility_ids = []
        for collector in collectors:
            if collector['agent_type'] == 'Individual' and collector.get('individual_id'):
                agent_id = self.create_agent('individual', collector['individual_id'], 'collector')
                if agent_id:
                    responsibility_ids.append(agent_id)
            elif collector['agent_type'] == 'Institution' and collector.get('institution_id'):
                agent_id = self.create_agent('institution', collector['institution_id'], 'collector')
                if agent_id:
                    responsibility_ids.append(agent_id)
        
        # Build result time
        result_time = None
        if sample_data.get('collection_start_date'):
            result_time = self.format_iso8601(sample_data['collection_start_date'])
        elif sample_data.get('collection_end_date'):
            result_time = self.format_iso8601(sample_data['collection_end_date'])
        
        # Build label
        label_parts = []
        if sample_data.get('cruise_field_prgrm_label'):
            label_parts.append(sample_data['cruise_field_prgrm_label'])
        if sample_data.get('launch_label'):
            label_parts.append(sample_data['launch_label'])
        elif sample_data.get('name'):
            label_parts.append(f"Collection of sample {sample_data['name']}")
        
        label = '; '.join(label_parts) if label_parts else 'Sampling event'
        
        # Create geospatial location
        geo_location_id = self.create_geospatial_location(sample_id, sample_data)
        
        # Create sampling site
        sampling_site_id = self.create_sampling_site(sample_id, sample_data)
        
        # Register and create row
        row_id = self.registry.register('SamplingEvent', key)
        
        row = self.get_blank_row()
        row['row_id'] = row_id
        row['otype'] = 'SamplingEvent'
        row['SamplingEvent.label'] = label
        row['SamplingEvent.description'] = description
        row['SamplingEvent.has_feature_of_interest'] = sample_data.get('locality_feature_type')
        row['SamplingEvent.project'] = sample_data.get('cruise_field_prgrm_label')
        row['SamplingEvent.result_time'] = result_time
        row['SamplingEvent.responsibility'] = responsibility_ids if responsibility_ids else None
        row['SamplingEvent.geo_location'] = [geo_location_id] if geo_location_id else None
        row['SamplingEvent.sampling_site'] = [sampling_site_id] if sampling_site_id else None
        
        self.rows.append(row)
        return row_id
    
