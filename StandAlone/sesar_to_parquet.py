    def process_sample(self, igsn: str):
        """Process a single sample and create all related objects."""
        # Get sample with all joins
        query = """
            SELECT s.*,
                   l.name as locality_name,
                   sft2.label as locality_feature_type,
                   sft.label as sampled_feature_label,
                   sft.feature_type_uri as sampled_feature_uri,
                   gmt.label as general_material_label,
                   gmt.material_type_uri as general_material_uri,
                   st.label as sample_type_label,
                   st.sample_type_uri as sample_type_uri_value,
                   cm.label as collection_method_label,
                   p.label as platform_label,
                   lp.label as launch_platform_label,
                   cfi.label as cruise_field_prgrm_label,
                   gay.label as geologic_age_younger_label,
                   gay.geologic_time_interval_uri as geologic_age_younger_uri,
                   gao.label as geologic_age_older_label,
                   gao.geologic_time_interval_uri as geologic_age_older_uri,
                   cr.individual_id as cur_registrant_individual_id,
                   cr.institution_id as cur_registrant_institution_id,
                   co.individual_id as cur_owner_individual_id,
                   co.institution_id as cur_owner_institution_id
            FROM sample s
            LEFT JOIN locality l ON s.locality_id = l.locality_id
            LEFT JOIN sampled_feature_type sft ON s.sampled_feature_type_id = sft.feature_type_id
            LEFT JOIN material_type gmt ON s.general_material_type_id = gmt.material_type_id
            LEFT JOIN sample_type st ON s.sample_type_id = st.sample_type_id
            LEFT JOIN sampling_method cm ON s.collection_method_id = cm.collection_method_id
            LEFT JOIN platform p ON s.platform_id = p.platform_id
            LEFT JOIN platform lp ON s.launch_platform_id = lp.platform_id
            LEFT JOIN initiative cfi ON s.cruise_field_prgrm_id = cfi.initiative_id
            LEFT JOIN geologic_time_scale gay ON s.geologic_age_younger_id = gay.geologic_time_id
            LEFT JOIN geologic_time_scale gao ON s.geologic_age_older_id = gao.geologic_time_id
            LEFT JOIN sesar_user cr ON s.cur_registrant_id = cr.sesar_user_id
            LEFT JOIN sesar_user co ON s.cur_owner_id = co.sesar_user_id
            LEFT JOIN sampled_feature_type sft2 ON L.feature_type_id = sft2.feature_type_id
           WHERE s.igsn = %s
        """
        
        sample = self.execute_pg_query_one(query, (igsn,))
        if not sample:
            logger.warning(f"Sample {igsn} not found")
            return
        
        sample_id = sample['sample_id']
        
        # Create MaterialSampleRecord
        sample_key = f"sample:{sample_id}"
        sample_row_id = self.registry.register('MaterialSampleRecord', sample_key)
        
        # Create related objects and collect their IDs
        
        # Context category
        context_category_ids = []
        if sample.get('sampled_feature_type_id'):
            concept_id = self.create_concept(
                'sampled_feature_type',
                sample['sampled_feature_type_id'],
                sample.get('sampled_feature_label', ''),
                'SESAR Sampled Feature Type',
                sample.get('sampled_feature_uri')
            )
            context_category_ids.append(concept_id)
        
        # Material categories
        material_category_ids = []
        if sample.get('general_material_type_id'):
            concept_id = self.create_concept(
                'material_type',
                sample['general_material_type_id'],
                sample.get('general_material_label', ''),
                'SESAR Material Type',
                sample.get('general_material_uri')
            )
            material_category_ids.append(concept_id)
        
        # Sample object type
        sample_obj_type_ids = []
        if sample.get('sample_type_id'):
            concept_id = self.create_concept(
                'sample_type',
                sample['sample_type_id'],
                sample.get('sample_type_label', ''),
                'SESAR Sample Type',
                sample.get('sample_type_uri_value')
            )
            sample_obj_type_ids.append(concept_id)
        
        # Keywords (geologic ages and unit)
        keyword_ids = []
        if sample.get('geologic_unit'):
            concept_id = self.create_concept(
                'geologic_unit',
                sample_id,
                sample['geologic_unit'],
                'Geologic Unit'
            )
            keyword_ids.append(concept_id)
        
        if sample.get('geologic_age_younger_id'):
            concept_id = self.create_concept(
                'geologic_time_younger',
                sample['geologic_age_younger_id'],
                sample.get('geologic_age_younger_label', ''),
                'Geologic Age Younger',
                identifier=sample.get('geologic_age_younger_uri')
            )
            keyword_ids.append(concept_id)
        
        if sample.get('geologic_age_older_id'):
            concept_id = self.create_concept(
                'geologic_time_older',
                sample['geologic_age_older_id'],
                sample.get('geologic_age_older_label', ''),
                'Geologic Age Older',
                identifier=sample.get('geologic_age_older_uri')
            )
            keyword_ids.append(concept_id)
        
        # Registrant
        registrant_ids = []
        if sample.get('cur_registrant_individual_id'):
            agent_id = self.create_agent('individual', sample['cur_registrant_individual_id'], 'registrant')
            if agent_id:
                registrant_ids.append(agent_id)
        elif sample.get('cur_registrant_institution_id'):
            agent_id = self.create_agent('institution', sample['cur_registrant_institution_id'], 'registrant')
            if agent_id:
                registrant_ids.append(agent_id)
        
        # Curation
        curation_ids = []
        curation_id = self.create_curation(sample_id, sample)
        if curation_id:
            curation_ids.append(curation_id)
        
        # Sampling event
        produced_by_ids = []
        event_id = self.create_sampling_event(sample_id, sample)
        if event_id:
            produced_by_ids.append(event_id)
        
        # Related resources (parent, children, siblings)
        related_resource_ids = []
        # This would require additional queries to get parent/child relationships
        
        # Build description
        desc_parts = []
        if sample.get('sample_description'):
            desc_parts.append(sample['sample_description'])
        if sample.get('size'):
            desc_parts.append(f"Sample size: {sample['size']}")
        
        description = '. '.join(desc_parts) if desc_parts else None
        
        # Create MaterialSampleRecord row
        row = self.get_blank_row()
        row['row_id'] = sample_row_id
        row['otype'] = 'MaterialSampleRecord'
        row['tcreated'] = time.time()
        row['MaterialSampleRecord.label'] = sample.get('name')
        row['MaterialSampleRecord.sample_identifier'] = sample.get('igsn')
        row['MaterialSampleRecord.description'] = description
        row['MaterialSampleRecord.last_modified_time'] = self.format_iso8601(sample.get('last_update_date'))
        row['MaterialSampleRecord.sampling_purpose'] = sample.get('purpose')
        row['MaterialSampleRecord.schema'] = 'iSamplesSchemaCore1.0.json'
        row['MaterialSampleRecord.has_context_category'] = context_category_ids if context_category_ids else None
        row['MaterialSampleRecord.has_material_category'] = material_category_ids if material_category_ids else None
        row['MaterialSampleRecord.has_sample_object_type'] = sample_obj_type_ids if sample_obj_type_ids else None
        row['MaterialSampleRecord.keywords'] = keyword_ids if keyword_ids else None
        row['MaterialSampleRecord.registrant'] = registrant_ids if registrant_ids else None
        row['MaterialSampleRecord.curation'] = curation_ids if curation_ids else None
        row['MaterialSampleRecord.produced_by'] = produced_by_ids if produced_by_ids else None
        row['MaterialSampleRecord.related_resource'] = related_resource_ids if related_resource_ids else None
        
        self.rows.append(row)
        logger.info(f"Processed sample {igsn} (row_id: {sample_row_id})")
    
    def process_all_samples(self, limit: Optional[int] = None):
        """Process all samples in the database."""
        query = "SELECT igsn FROM sample"
        if limit:
            query += f" LIMIT {limit}"
        
        samples = self.execute_pg_query(query)
        logger.info(f"Processing {len(samples)} samples")
        
        for i, sample in enumerate(samples, 1):
            self.process_sample(sample['igsn'])
            if i % 100 == 0:
                logger.info(f"Processed {i}/{len(samples)} samples")
    
    def write_to_duckdb(self):
        """Write all rows to DuckDB."""
        if not self.rows:
            logger.warning("No rows to write")
            return
        
        logger.info(f"Writing {len(self.rows)} rows to DuckDB")
        
        # Insert rows in batches
        batch_size = 1000
        for i in range(0, len(self.rows), batch_size):
            batch = self.rows[i:i+batch_size]
            self.duck_conn.executemany(
                "INSERT INTO samples VALUES (" + ",".join(["?"] * len(self.get_blank_row())) + ")",
                [tuple(row.values()) for row in batch]
            )
            self.duck_conn.commit()
        
        logger.info("Data written to DuckDB")
    
    def export_to_parquet(self):
        """Export DuckDB table to Parquet file."""
        output_path = pathlib.Path(self.config.output_parquet)
        
        query = f"""
            COPY samples TO '{output_path}' (FORMAT PARQUET)
        """
        
        self.duck_conn.execute(query)
        logger.info(f"Exported to {output_path}")
    
    def run(self, limit: Optional[int] = None):
        """Main execution method."""
        try:
            self.connect_postgres()
            self.connect_duckdb()
            
            self.process_all_samples(limit=limit)
            self.write_to_duckdb()
            self.export_to_parquet()
            
            logger.info("Conversion complete!")
            
        finally:
            if self.pg_conn:
                self.pg_conn.close()
            if self.duck_conn:
                self.duck_conn.close()


