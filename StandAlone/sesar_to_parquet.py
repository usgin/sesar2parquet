    def create_geospatial_location(self, sample_id: int, sample_data: Dict) -> Optional[int]:
        """Create GeospatialCoordLocation and return its row_id."""
        lat = sample_data.get('latitude')
        lon = sample_data.get('longitude')
        
        if not lat and not lon:
            return None
        
        key = f"sample:{sample_id}"
        
        # Check if already created
        existing_id = self.registry.get_id('GeospatialCoordLocation', key)
        if existing_id:
            return existing_id
        
        # Build elevation string
        elev_parts = []
        if sample_data.get('elevation'):
            elev_parts.append(str(sample_data['elevation']))
            if sample_data.get('elevation_uom'):
                elev_parts.append(f"UOM: {sample_data['elevation_uom']}")
        
        depth_min = sample_data.get('depth_min')
        depth_max = sample_data.get('depth_max')
        
        if depth_min or depth_max:
            if depth_min == depth_max:
                elev_parts.append(f"Depth: {depth_min}")
            elif depth_min and depth_max:
                elev_parts.append(f"Depth range: {depth_min} to {depth_max}")
            elif depth_min:
                elev_parts.append(f"Depth minimum: {depth_min}")
            elif depth_max:
                elev_parts.append(f"Depth maximum: {depth_max}")
            
            if sample_data.get('depth_uom'):
                elev_parts.append(f"UOM: {sample_data['depth_uom']}")
        
        elevation = ' '.join(elev_parts) if elev_parts else None
        
        # Register and create row
        row_id = self.registry.register('GeospatialCoordLocation', key)
        
        row = self.get_blank_row()
        row['row_id'] = row_id
        row['otype'] = 'GeospatialCoordLocation'
        row['GeospatialCoordLocation.latitude'] = float(lat) if lat else None
        row['GeospatialCoordLocation.longitude'] = float(lon) if lon else None
        row['GeospatialCoordLocation.elevation'] = elevation
        row['GeospatialCoordLocation.obfuscated'] = False
        
        self.rows.append(row)
        return row_id
    
