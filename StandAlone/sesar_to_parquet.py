class ObjectRegistry:
    """Registry to track objects and assign unique row IDs."""
    
    def __init__(self):
        self.objects: Dict[str, Dict[str, int]] = {}  # {otype: {object_key: row_id}}
        self.next_id = 1
    
    def register(self, otype: str, key: str) -> int:
        """Register an object and get its row_id."""
        if otype not in self.objects:
            self.objects[otype] = {}
        
        if key not in self.objects[otype]:
            self.objects[otype][key] = self.next_id
            self.next_id += 1
        
        return self.objects[otype][key]
    
    def get_id(self, otype: str, key: str) -> Optional[int]:
        """Get row_id for an existing object."""
        return self.objects.get(otype, {}).get(key)


