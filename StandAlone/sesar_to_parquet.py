    def create_agent(self, agent_type: str, agent_id: int, role: str = '') -> Optional[int]:
        """Create an Agent object and return its row_id."""
        key = f"{agent_type}:{agent_id}"
        
        # Check if already created
        existing_id = self.registry.get_id('Agent', key)
        if existing_id:
            return existing_id
        
        # Get agent data
        if agent_type == 'individual':
            query = "SELECT * FROM individual WHERE individual_id = %s"
        elif agent_type == 'institution':
            query = "SELECT * FROM institution WHERE institution_id = %s"
        else:
            return None
        
        agent_data = self.execute_pg_query_one(query, (agent_id,))
        if not agent_data:
            return None
        
        # Register and create row
        row_id = self.registry.register('Agent', key)
        
        row = self.get_blank_row()
        row['row_id'] = row_id
        row['otype'] = 'Agent'
        
        # Determine name
        if agent_type == 'individual':
            name = (agent_data.get('label') or agent_data.get('individual_uri') or 
                   agent_data.get('description') or agent_data.get('email'))
            identifier = agent_data.get('individual_uri')
        else:  # institution
            name = (agent_data.get('label') or agent_data.get('description') or 
                   agent_data.get('email'))
            identifier = None
        
        # Build contact info
        contact_parts = []
        if agent_data.get('address'):
            contact_parts.append(f"postal: {agent_data['address']}")
        if agent_data.get('email'):
            contact_parts.append(f"email: {agent_data['email']}")
        if agent_data.get('phone'):
            contact_parts.append(f"Phone: {agent_data['phone']}")
        
        row['Agent.name'] = name
        row['Agent.identifier'] = identifier
        row['Agent.contact_information'] = ', '.join(contact_parts) if contact_parts else None
        row['Agent.role'] = role
        row['Agent.affiliation'] = None
        
        self.rows.append(row)
        return row_id
    
