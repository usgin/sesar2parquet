    def execute_pg_query(self, query: str, params: tuple = None) -> List[Dict]:
        """Execute PostgreSQL query and return results."""
        with self.pg_conn.cursor(cursor_factory=RealDictCursor) as cursor:
            cursor.execute(query, params)
            return cursor.fetchall()
    
    def execute_pg_query_one(self, query: str, params: tuple = None) -> Optional[Dict]:
        """Execute PostgreSQL query and return single result."""
        with self.pg_conn.cursor(cursor_factory=RealDictCursor) as cursor:
            cursor.execute(query, params)
            result = cursor.fetchone()
            return dict(result) if result else None
    
    def format_iso8601(self, date_value) -> Optional[str]:
        """Convert date to ISO8601 format."""
        if not date_value:
            return None
        
        try:
            if isinstance(date_value, datetime):
                return date_value.isoformat()
            if isinstance(date_value, str):
                dt = datetime.fromisoformat(date_value)
                return dt.isoformat()
            return str(date_value).replace(' ', 'T', 1)
        except Exception:
            return str(date_value).replace(' ', 'T', 1) if date_value else None
    
